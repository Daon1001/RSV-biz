# ── HTML 조각 헬퍼 ────────────────────────────────────────────
def _ed(ph="", cls="", h="h"):
    c = f' class="{cls}"' if cls else ""
    p = f' data-ph="{ph}"' if ph else ""
    return f'<td{c} contenteditable="true" spellcheck="false"{p}></td>'


def H(text):
    return f'<h3 class="sub">{text}</h3>'


def KV(rows):
    """rows: [(라벨, 폭mm|None, 플레이스홀더, colspan)] 를 2열 구조로"""
    out = ['<table>']
    for r in rows:
        lab, ph, span = r[0], r[1], r[2]
        out.append(f'<tr><td class="lb">{lab}</td>'
                   f'{_ed(ph)[:4]}{"" if span == 1 else f" colspan={span}"}'.replace("<td", "<td", 1))
        out[-1] = (f'<tr><td class="lb">{lab}</td>'
                   f'<td colspan="{span}" contenteditable="true" spellcheck="false"'
                   f'{f" data-ph=\"{ph}\"" if ph else ""} class="h"></td></tr>')
    out.append('</table>')
    return "".join(out)


def T(cols, n, tall=False, note=None):
    """cols: [(헤더, 폭mm|None, 플레이스홀더)] · n: 데이터 행 수"""
    hd = "".join(
        f'<th{f" style=\"width:{w}mm\"" if w else ""}>{h}</th>' for h, w, _ in cols)
    cls = "hh" if tall else "h"
    rows = []
    for _ in range(n):
        tds = []
        for i, (_, _, ph) in enumerate(cols):
            p = f' data-ph="{ph}"' if ph else ""
            tds.append(f'<td class="{cls}" contenteditable="true" '
                       f'spellcheck="false"{p}></td>')
        rows.append("<tr>" + "".join(tds) + "</tr>")
    return f'<table><tr>{hd}</tr>{"".join(rows)}</table>'


def FREE(h=26):
    return (f'<table><tr><td style="height:{h}mm" contenteditable="true" '
            f'spellcheck="false"></td></tr></table>')


def NOTE(t):
    return f'<div class="note">{t}</div>'


