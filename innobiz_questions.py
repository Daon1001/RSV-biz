def is_fin(no):
    """경영실적 재무지표(3단계) 문항 여부"""
    return 51 <= no <= 58


def options(no):
    return Q_BY_NO[no][5]


def weights(no):
    return W3 if is_fin(no) else W5


def score(answers):
    """answers: {문항번호: 선택 인덱스(0=A)} → 채점 결과"""
    grp = {}
    for code, part, name, alloc, cnt in GROUPS:
        grp[code] = dict(code=code, part=part, name=name, alloc=alloc,
                         got=0.0, cnt=cnt, items=[])

    for no, gc, pt, label, q, opts, ev in QUESTIONS:
        w = weights(no)
        i = int(answers.get(no, len(w) - 1))
        i = min(max(i, 0), len(w) - 1)
        got = pt * w[i]
        grp[gc]["got"] += got
        grp[gc]["items"].append(dict(no=no, idx=i, pt=pt, got=got, lost=pt - got,
                                     label=label, q=q, opts=opts, ev=ev,
                                     sel=opts[i] if i < len(opts) else ""))

    for v in grp.values():
        v["rate"] = v["got"] / v["alloc"] if v["alloc"] else 0
        v["lost"] = v["alloc"] - v["got"]

    part = {}
    for code, name, alloc, cnt in PARTS:
        g = sum(v["got"] for v in grp.values() if v["part"] == code)
        part[code] = dict(got=g, alloc=alloc, rate=g / alloc, name=name)

    total = sum(v["got"] for v in grp.values())
    verdict = next(v for v in VERDICTS if total >= v[0])

    return dict(sections=grp, parts=part, total=total,
                verdict=dict(label=verdict[1], desc=verdict[2], color=verdict[3]),
                gap650=max(0, 650 - total), gap700=max(0, 700 - total),
                gap800=max(0, 800 - total))
