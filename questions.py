def is_perf(sec_code):
    return SEC_BY_CODE[sec_code][5]


def labels(sec_code):
    return LABELS_PERF if is_perf(sec_code) else LABELS_STD


def label_desc(sec_code):
    return LABELS_PERF_DESC if is_perf(sec_code) else LABELS_STD_DESC


def score(answers):
    """answers: {문항번호: 등급(0~3)} → 채점 결과 dict"""
    sec = {}
    for code, part, name, alloc, cnt, perf in SECTIONS:
        sec[code] = dict(code=code, part=part, name=name, alloc=alloc,
                         got=0.0, cnt=cnt, perf=perf, items=[])

    for no, sc, pt, qtext, ev in QUESTIONS:
        g = int(answers.get(no, 0))
        got = pt * GRADE_W[g]
        sec[sc]["got"] += got
        sec[sc]["items"].append(dict(no=no, grade=g, pt=pt, got=got,
                                     lost=pt - got, q=qtext, ev=ev))

    for v in sec.values():
        v["rate"] = v["got"] / v["alloc"] if v["alloc"] else 0
        v["lost"] = v["alloc"] - v["got"]

    part = {}
    for p in ("Ⅰ", "Ⅱ", "Ⅲ"):
        g = sum(v["got"] for v in sec.values() if v["part"] == p)
        part[p] = dict(got=g, alloc=PART_TOTAL[p], rate=g / PART_TOTAL[p],
                       name=PART_NAME[p])

    total = sum(v["got"] for v in sec.values())
    verdict = next(v for v in VERDICTS if total >= v[0])

    return dict(sections=sec, parts=part, total=total,
                verdict=dict(label=verdict[1], desc=verdict[2], color=verdict[3]),
                gap700=max(0, 700 - total), gap780=max(0, 780 - total))


def priorities(result, top=5):
    """구간별 실점 기준 보완 우선순위"""
    rows = sorted(result["sections"].values(), key=lambda v: -v["lost"])
    return rows[:top]


def weak_questions(result, threshold=3):
    """등급이 threshold 미만인 문항 번호 목록"""
    out = []
    for v in result["sections"].values():
        for it in v["items"]:
            if it["grade"] < threshold:
                out.append(it["no"])
    return sorted(out)
